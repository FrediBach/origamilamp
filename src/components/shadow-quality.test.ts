import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createShadowQualityController } from './shadow-quality'

describe('demand-rendered shadow quality', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  function setup(options: { enabled?: boolean, animated?: boolean, visible?: boolean, interacting?: boolean } = {}) {
    const samples = { value: 5 }, invalidate = vi.fn()
    const controller = createShadowQualityController({ samples, invalidate, enabled: true, animated: false, ...options })
    return { samples, invalidate, controller }
  }

  it('keeps ordinary scenes at the native five-sample baseline with no idle work', () => {
    const { samples, invalidate, controller } = setup({ enabled: false })
    controller.reset()
    vi.advanceTimersByTime(1000)
    expect(samples.value).toBe(5)
    expect(invalidate).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    controller.dispose()
  })

  it('renders only three finite refinements after interaction', () => {
    const { samples, invalidate, controller } = setup()
    expect(samples.value).toBe(8)
    vi.advanceTimersByTime(119)
    expect(samples.value).toBe(8)
    vi.advanceTimersByTime(1)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(229)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(1)
    expect(samples.value).toBe(64)
    expect(invalidate).toHaveBeenCalledTimes(3)
    vi.advanceTimersByTime(299)
    expect(samples.value).toBe(64)
    vi.advanceTimersByTime(1)
    expect(samples.value).toBe(256)
    expect(invalidate).toHaveBeenCalledTimes(4)
    vi.advanceTimersByTime(10_000)
    expect(invalidate).toHaveBeenCalledTimes(4)
    expect(vi.getTimerCount()).toBe(0)
    controller.dispose()
  })

  it('cancels stale refinements when camera, scene, or size changes reset quality', () => {
    const { samples, controller } = setup()
    vi.advanceTimersByTime(200)
    expect(samples.value).toBe(24)
    controller.reset()
    expect(samples.value).toBe(8)
    vi.advanceTimersByTime(150)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(199)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(1)
    expect(samples.value).toBe(64)
    vi.advanceTimersByTime(100)
    expect(samples.value).toBe(64)
    vi.advanceTimersByTime(199)
    expect(samples.value).toBe(64)
    vi.advanceTimersByTime(1)
    expect(samples.value).toBe(256)
    controller.dispose()
  })

  it('holds eight samples throughout a gesture and refines only after it ends', () => {
    const { samples, controller } = setup()
    vi.advanceTimersByTime(650)
    controller.setInteracting(true)
    expect(samples.value).toBe(8)
    controller.reset()
    vi.advanceTimersByTime(1000)
    expect(samples.value).toBe(8)
    expect(vi.getTimerCount()).toBe(0)
    controller.setInteracting(false)
    vi.advanceTimersByTime(120)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(230)
    expect(samples.value).toBe(64)
    vi.advanceTimersByTime(300)
    expect(samples.value).toBe(256)
    controller.dispose()
  })

  it('lets flicker settle at 24 samples without scheduling the expensive final stage', () => {
    const { samples, invalidate, controller } = setup({ animated: true })
    vi.advanceTimersByTime(120)
    expect(samples.value).toBe(24)
    vi.advanceTimersByTime(1000)
    expect(samples.value).toBe(24)
    expect(vi.getTimerCount()).toBe(0)
    expect(invalidate).toHaveBeenCalledTimes(2)
    controller.setInteracting(true)
    expect(samples.value).toBe(8)
    controller.setInteracting(false)
    vi.advanceTimersByTime(350)
    expect(samples.value).toBe(24)
    controller.dispose()
  })

  it('pauses hidden or offscreen previews and resumes even if a gesture ended while hidden', () => {
    const { samples, invalidate, controller } = setup()
    controller.setInteracting(true)
    controller.setVisible(false)
    invalidate.mockClear()
    vi.advanceTimersByTime(1000)
    expect(invalidate).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    controller.setVisible(true)
    expect(invalidate).toHaveBeenCalledTimes(1)
    vi.advanceTimersByTime(650)
    expect(samples.value).toBe(256)
    controller.dispose()
  })

  it('cancels the final expensive refinement when hidden or disposed after an earlier stage', () => {
    const { samples, invalidate, controller } = setup()
    vi.advanceTimersByTime(350)
    expect(samples.value).toBe(64)
    controller.setVisible(false)
    invalidate.mockClear()
    vi.advanceTimersByTime(1000)
    expect(samples.value).toBe(8)
    expect(invalidate).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    controller.setVisible(true)
    vi.advanceTimersByTime(350)
    expect(samples.value).toBe(64)
    controller.dispose()
    invalidate.mockClear()
    vi.advanceTimersByTime(1000)
    expect(samples.value).toBe(64)
    expect(invalidate).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })

  it('does no hidden initial work and cancels all work on disposal', () => {
    const { samples, invalidate, controller } = setup({ visible: false })
    expect(samples.value).toBe(8)
    expect(vi.getTimerCount()).toBe(0)
    expect(invalidate).not.toHaveBeenCalled()
    controller.setVisible(true)
    controller.dispose()
    invalidate.mockClear()
    vi.advanceTimersByTime(1000)
    controller.reset()
    controller.setVisible(false)
    controller.setInteracting(true)
    expect(invalidate).not.toHaveBeenCalled()
    expect(samples.value).toBe(8)
    expect(vi.getTimerCount()).toBe(0)
  })
})
