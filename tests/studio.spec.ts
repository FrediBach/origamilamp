test('light sources have independent heights, warmth, clearance and reusable recipe settings', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const setControl = async (name: string, value: string) => {
    const control = page.getByRole('spinbutton', { name, exact: true })
    await control.fill(value)
    await control.press('Tab')
    await expect(control).toHaveValue(value)
  }
  await page.goto('/')
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  const led = page.getByRole('button', { name: 'LED column', exact: true })
  const oneBulb = page.getByRole('button', { name: 'One bulb', exact: true })
  const twoBulbs = page.getByRole('button', { name: 'Two bulbs', exact: true })
  const height = page.getByRole('spinbutton', { name: 'Bulb height (percent)', exact: true })
  const secondHeight = page.getByRole('spinbutton', { name: 'Second bulb height (percent)', exact: true })
  const warmth = page.getByRole('spinbutton', { name: 'Light warmth (kelvin)', exact: true })
  const bulbDiameter = page.getByRole('spinbutton', { name: 'Bulb diameter (millimetres)', exact: true })
  await expect(led).toHaveAttribute('aria-pressed', 'true')
  await expect(height).toHaveCount(0)
  await expect(secondHeight).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'LED module diameter (millimetres)', exact: true })).toHaveValue('32')

  await oneBulb.click()
  await expect(oneBulb).toHaveAttribute('aria-pressed', 'true')
  await expect(led).toHaveAttribute('aria-pressed', 'false')
  await expect(bulbDiameter).toHaveValue('60')
  await expect(secondHeight).toHaveCount(0)
  await setControl('Bulb height (percent)', '75')
  await setControl('Light warmth (kelvin)', '1800')
  await expect(page.getByRole('slider', { name: 'Light warmth (kelvin)', exact: true })).toHaveAttribute('aria-valuenow', '1800')
  await page.getByRole('button', { name: 'Studio', exact: true }).click()
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible()
  const bounds = await canvas.boundingBox()
  expect(bounds).not.toBeNull()
  // Orbit with the same pointer gesture offered to users, to expose the core.
  const centerX = bounds!.x + bounds!.width / 2
  const centerY = bounds!.y + bounds!.height / 2
  await page.mouse.move(centerX, centerY)
  await page.mouse.down()
  await page.mouse.move(centerX + 45, centerY + bounds!.height * 0.16, { steps: 12 })
  await page.mouse.up()
  await canvas.screenshot({ path: 'test-results/light-one-bulb-warm.png' })
  await setControl('Light warmth (kelvin)', '6500')
  await canvas.screenshot({ path: 'test-results/light-one-bulb-cool.png' })
  await setControl('Light warmth (kelvin)', '1800')

  await twoBulbs.click()
  await expect(twoBulbs).toHaveAttribute('aria-pressed', 'true')
  await expect(oneBulb).toHaveAttribute('aria-pressed', 'false')
  await expect(height).toHaveValue('75')
  await setControl('Second bulb height (percent)', '75')
  await expect(height).toHaveValue('75')
  await expect(page.getByText('The bulbs overlap at these heights. Move them farther apart.', { exact: true })).toBeVisible()
  await setControl('Bulb height (percent)', '25')
  await expect(height).toHaveValue('25')
  await expect(secondHeight).toHaveValue('75')
  const firstHeightSlider = page.getByRole('slider', { name: 'Bulb height (percent)', exact: true })
  const secondHeightSlider = page.getByRole('slider', { name: 'Second bulb height (percent)', exact: true })
  await expect(firstHeightSlider).toHaveAttribute('aria-valuenow', '25')
  await expect(secondHeightSlider).toHaveAttribute('aria-valuenow', '75')
  await expect.poll(async () => {
    const first = await firstHeightSlider.boundingBox()
    const second = await secondHeightSlider.boundingBox()
    return first !== null && second !== null && first.x < second.x
  }).toBe(true)
  await expect(page.getByText('The bulbs overlap at these heights. Move them farther apart.', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/light-controls-desktop.png', fullPage: true })
  await canvas.screenshot({ path: 'test-results/light-two-bulbs-warm.png' })
  await setControl('Light warmth (kelvin)', '6500')
  await canvas.screenshot({ path: 'test-results/light-two-bulbs-cool.png' })
  const light = page.getByRole('switch', { name: 'Preview light', exact: true })
  await light.click()
  await expect(light).not.toBeChecked()
  await canvas.screenshot({ path: 'test-results/light-two-bulbs-off.png' })
  await light.click()
  await expect(light).toBeChecked()

  await setControl('Bulb diameter (millimetres)', '100')
  await setControl('Required radial clearance (millimetres)', '15')
  await expect(page.getByRole('region', { name: 'Live feasibility checks' })).toContainText('Mounting clamps reduce light clearance')
  await setControl('Bulb diameter (millimetres)', '72')
  await expect(page.getByRole('region', { name: 'Live feasibility checks' })).not.toContainText('Mounting clamps reduce light clearance')
  await page.reload()
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  await expect(twoBulbs).toHaveAttribute('aria-pressed', 'true')
  await expect(height).toHaveValue('25')
  await expect(secondHeight).toHaveValue('75')
  await expect(warmth).toHaveValue('6500')
  await expect(bulbDiameter).toHaveValue('72')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  const recipePath = await (await downloadPromise).path()
  expect(recipePath).not.toBeNull()
  await led.click()
  await expect(height).toHaveCount(0)
  await expect(secondHeight).toHaveCount(0)
  await expect(page.getByRole('spinbutton', { name: 'LED module diameter (millimetres)', exact: true })).toHaveValue('32')
  await setControl('Light warmth (kelvin)', '2700')
  await page.getByLabel('Import a saved design recipe', { exact: true }).setInputFiles(recipePath!)
  await expect(twoBulbs).toHaveAttribute('aria-pressed', 'true')
  await expect(height).toHaveValue('25')
  await expect(secondHeight).toHaveValue('75')
  await expect(warmth).toHaveValue('6500')
  await expect(bulbDiameter).toHaveValue('72')
  await expect(page.getByRole('spinbutton', { name: 'Required radial clearance (millimetres)', exact: true })).toHaveValue('15')
  await expect(canvas).toBeVisible()
  await expect(page.getByText('3D preview is unavailable', { exact: true })).not.toBeVisible()
  expect(errors).toEqual([])
})

