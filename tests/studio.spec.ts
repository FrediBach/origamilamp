import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('studio renders, edits live, persists, inspects layers and exports a calibration assembly', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your lamp', exact: true })).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await page.screenshot({ path: 'test-results/studio-desktop.png', fullPage: true })
  await page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true }).fill('190')
  await page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true }).press('Tab')
  await expect(page.getByLabel('Design dimensions and print views')).toContainText('190')
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true })).toHaveValue('190')
  await page.getByRole('button', { name: 'Layers', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  const layerAccessibility = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(layerAccessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
  await page.screenshot({ path: 'test-results/layer-inspector.png' })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.getByRole('button', { name: 'Layers', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Materials', exact: true }).click()
  await expect(page.getByRole('region', { name: /^Compressed manufacturing model/ })).toBeVisible()
  await page.getByRole('button', { name: 'Section', exact: true }).click()
  await page.screenshot({ path: 'test-results/manufacturing-section.png' })
  await page.getByRole('button', { name: 'Prepare to make' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Start with a calibration print' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('origami-lamp-calibration.zip')
  expect(errors).toEqual([])
})

test('keyboard controls, experimental export guard and accessibility', async ({ page }) => {
  await page.goto('/')
  const help = page.getByRole('button', { name: 'Help: the process', exact: true })
  await help.focus()
  await help.press('Enter')
  await expect(page.getByRole('dialog', { name: 'A flat print. A softer space.' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(help).toBeFocused()
  const width = page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true })
  await width.fill('999')
  await width.press('Escape')
  await expect(width).toHaveValue('180')
  const widthSlider = page.getByRole('slider', { name: 'Width (millimetres)', exact: true })
  await widthSlider.focus()
  await widthSlider.press('ArrowRight')
  await expect(width).toHaveValue('181')
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
  await page.getByRole('button', { name: 'Polygon', exact: true }).click()
  await expect(page.getByText('Appearance study · manufacturing export paused for this form')).toBeVisible()
  await page.getByRole('button', { name: 'Prepare to make' }).click()
  await expect(page.getByRole('button', { name: 'Export the full design' })).toBeDisabled()
  const exportAccessibility = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(exportAccessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
})

