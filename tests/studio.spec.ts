test('printability corrections explain changes, support undo, and persist on mobile', async ({ page }) => {
  await page.goto('/')
  const membraneWidth = page.getByRole('spinbutton', { name: 'Membrane width (millimetres)', exact: true })
  await membraneWidth.fill('40')
  await membraneWidth.press('Tab')
  await page.getByRole('button', { name: 'View checks', exact: true }).click()

  const dialog = page.getByRole('dialog', { name: 'Room for a little confidence.' })
  const cornerWarning = dialog.locator('.check-row').filter({ has: page.getByRole('heading', { name: 'Corner offsets need more room', exact: true }) })
  await expect(cornerWarning.locator('.check-correction')).toContainText(/corner radius/i)
  await expect(cornerWarning.getByRole('button')).toBeVisible()
  for (const title of ['Physical validation pending', 'Attachment load needs a physical test']) {
    const physicalWarning = dialog.locator('.check-row').filter({ has: page.getByRole('heading', { name: title, exact: true }) })
    await expect(physicalWarning).toBeAttached()
    await expect(physicalWarning.getByRole('button')).toHaveCount(0)
  }
  await page.screenshot({ path: 'test-results/printability-correction-desktop.png' })

  await cornerWarning.getByRole('button').click()
  await expect(dialog).toBeVisible()
  await expect(cornerWarning).toHaveCount(0)
  await expect(dialog.getByRole('heading', { name: 'Aperture stays open', exact: true })).toBeVisible()
  await expect(dialog.getByRole('status')).toBeVisible()
  await expect(dialog.getByRole('status')).toBeFocused()
  await dialog.getByRole('button', { name: 'Undo correction', exact: true }).click()
  await expect(cornerWarning).toBeVisible()

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(cornerWarning.getByRole('button')).toBeVisible()
  await cornerWarning.getByRole('button').scrollIntoViewIfNeeded()
  const bounds = await dialog.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  const accessibility = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(accessibility.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
  await page.screenshot({ path: 'test-results/printability-correction-mobile.png' })

  await cornerWarning.getByRole('button').click()
  await expect(cornerWarning).toHaveCount(0)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(membraneWidth).toHaveValue('40')
  await page.getByText('Fine-tune your form', { exact: true }).click()
  const cornerRadius = page.getByRole('spinbutton', { name: 'Corner radius (millimetres)', exact: true })
  const correctedRadius = await cornerRadius.inputValue()
  expect(Number(correctedRadius)).toBeGreaterThan(40.05)
  expect(Number(correctedRadius)).toBeLessThan(89.95)
  await page.reload()
  await expect(membraneWidth).toHaveValue('40')
  await page.getByText('Fine-tune your form', { exact: true }).click()
  await expect(cornerRadius).toHaveValue(correctedRadius)
  await page.getByRole('button', { name: 'View checks', exact: true }).click()
  await expect(cornerWarning).toHaveCount(0)
  await expect(dialog.getByRole('heading', { name: 'Aperture stays open', exact: true })).toBeVisible()
})

test('mounting correction preserves the selected LED clearance and enables export', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  const diameter = page.getByRole('spinbutton', { name: 'LED module diameter (millimetres)', exact: true })
  const clearance = page.getByRole('spinbutton', { name: 'Required radial clearance (millimetres)', exact: true })
  await diameter.fill('100')
  await diameter.press('Tab')
  await clearance.fill('15')
  await clearance.press('Tab')
  await page.getByRole('button', { name: 'Prepare to make' }).click()
  await expect(page.getByRole('button', { name: 'Export the full design' })).toBeDisabled()
  await page.getByRole('button', { name: 'Review checks', exact: true }).click()

  const dialog = page.getByRole('dialog', { name: 'Room for a little confidence.' })
  const mountingWarning = dialog.locator('.check-row').filter({ has: page.getByRole('heading', { name: 'Mounting clamps reduce light clearance', exact: true }) })
  await expect(mountingWarning.locator('.check-correction p')).not.toBeEmpty()
  await mountingWarning.getByRole('button').click()
  await expect(mountingWarning).toHaveCount(0)
  await expect(dialog.getByRole('heading', { name: 'Light fits through the mounting clamps', exact: true })).toBeVisible()
  await expect(dialog.locator('.check-error')).toHaveCount(0)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(diameter).toHaveValue('100')
  await expect(clearance).toHaveValue('15')
  await page.getByRole('button', { name: 'Prepare to make' }).click()
  await expect(page.getByRole('button', { name: 'Export the full design' })).toBeEnabled()
})
