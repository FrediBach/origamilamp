import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('optional electronics box configures usable space, persists, imports and works with springs', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  const box = page.getByRole('switch', { name: 'Wooden electronics box', exact: true })
  const height = page.getByRole('spinbutton', { name: 'Internal box height (millimetres)', exact: true })
  await expect(box).not.toBeChecked()
  await expect(height).toBeHidden()
  await box.focus()
  await box.press('Space')
  await expect(box).toBeChecked()
  await expect(height).toHaveValue('40')
  await expect(page.locator('.base-dimensions')).toContainText('195 × 195 × 40 mm')
  await height.fill('80')
  await height.press('Tab')
  await expect(page.locator('.base-dimensions')).toContainText('195 × 195 × 80 mm')
  await box.click()
  await expect(height).toBeHidden()
  await box.click()
  await expect(height).toHaveValue('80')

  await page.getByRole('tab', { name: 'Form', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true }).fill('220')
  await page.getByRole('spinbutton', { name: 'Width (millimetres)', exact: true }).press('Tab')
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  await expect(page.locator('.base-dimensions')).toContainText('235 × 195 × 80 mm')
  await page.getByRole('button', { name: 'Studio', exact: true }).click()
  await height.scrollIntoViewIfNeeded()
  await expect(page.locator('canvas')).toBeVisible()
  await page.screenshot({ path: 'test-results/electronics-box-bolted.png', fullPage: true })

  await page.getByText('Top and bottom mounting', { exact: true }).click()
  await page.getByRole('button', { name: 'Metal springs', exact: true }).click()
  await height.scrollIntoViewIfNeeded()
  const accessibility = await new AxeBuilder({ page }).include('.base-controls').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(accessibility.violations).toEqual([])
  await page.screenshot({ path: 'test-results/electronics-box-springs.png', fullPage: true })

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  const recipePath = await (await downloadPromise).path()
  expect(recipePath).toBeTruthy()
  await page.reload()
  await page.getByRole('tab', { name: 'Finish', exact: true }).click()
  await expect(box).toBeChecked()
  await expect(height).toHaveValue('80')
  await page.getByRole('button', { name: 'Reset all design settings', exact: true }).click()
  await expect(box).not.toBeChecked()
  await page.getByLabel('Import a saved design recipe').setInputFiles(recipePath!)
  await expect(box).toBeChecked()
  await expect(height).toHaveValue('80')
  await expect(page.locator('.mounting-preview-label')).toHaveText('Top + bottom springs · suspension concept')

  await page.setViewportSize({ width: 390, height: 844 })
  await height.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/electronics-box-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
